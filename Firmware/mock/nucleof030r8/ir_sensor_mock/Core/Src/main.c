/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
  fifo_init(&fifo_buffer);
  fifo_init(&fifo_pd2);
  ir_adc_init(&ir_adc_config, &ir_adc_context);
  init_log_buffer();
  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_ADC_Init();
  MX_RTC_Init();
  MX_TIM1_Init();
  MX_USART1_UART_Init();
  MX_USART2_UART_Init();
  MX_TIM3_Init();
  /* USER CODE BEGIN 2 */
  HAL_ADC_Start_DMA(&hadc, adc_buffer, NUM_PHOTODIODES);
  HAL_UART_Init(&huart1);
  HAL_UART_Receive_DMA(&huart1, rs485_buffer, 4);
  //HAL_TIM_Base_Start_IT(&htim3);
  HAL_TIM_OC_Start_IT(&htim3, TIM_CHANNEL_1);
  HAL_TIM_OC_Start_IT(&htim3, TIM_CHANNEL_2);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */

    // FSM update task run at 100Hz
    if(fsm_tick) {
      if(comms.rs485_flag) {
        read_packet(rs485_buffer, &(comms.rs485_msg));
      }
      update_fsm(&fifo_buffer, &comms);
      fsm_tick = 0;
      comms.rs485_flag = 0;
    }

    // ADC constantly runs in the background via DMA
    if(adc_tick) {
      adc_conversion_complete_callback(&ir_adc_context, &fifo_buffer, adc_buffer);
      adc_tick = 0;
    }
    
    // UART logger runs at 1Hz
    if(logger_tick) {
      output_from_fsm(UART_TX, msg_buf_a, &msg_buf_a_len, LOG_BUFFER_SIZE);
      push_log(msg_buf_a, msg_buf_a_len);
      logger_tick = 0;
    }

    
    // default task to just drain the data into serial.
    pop_log(&huart2);

  }
  /* USER CODE END 3 */
}

